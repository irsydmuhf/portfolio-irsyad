/** Options for the admin picker, sorted by display title. */
export const TECH_ICON_OPTIONS = Object.entries(TECH_ICONS)
  .map(([slug, icon]) => ({ slug, title: icon.title }))
  .sort((a, b) => a.title.localeCompare(b.title));

export function techIcon(slug: string): SimpleIcon | undefined {
  return slug && Object.hasOwn(TECH_ICONS, slug) ? TECH_ICONS[slug] : undefined;
}
